const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const Module = require('node:module');
require.extensions['.ts'] = require.extensions['.tsx'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.React,esModuleInterop:true,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {hasRight,canAccessPage,normalizePermissions,toggleRight} = require('../src/utils/permissions');
const {permissionModules} = require('../src/config/rolePermissions');
const keys=permissionModules.flatMap(group=>group.permissions.map(p=>p.key));
assert.equal(new Set(keys).size,keys.length);
for(const key of ['view','edit','settings','import','manage_notifications']) assert.ok(!keys.includes(key));
assert.ok(canAccessPage(['view_openings'],'table'));
assert.ok(canAccessPage(['view_roles'],'roles'));
assert.ok(!canAccessPage(['view_users'],'roles'));
assert.ok(!canAccessPage(['manage_roles'],'roles'));
assert.ok(!canAccessPage(['settings'],'integrations'));
assert.ok(canAccessPage(['settings'],'settings'));
assert.ok(!hasRight(['edit_closures'],'edit_closures'));
assert.deepEqual(normalizePermissions(['view','view_openings']),['view_openings']);
assert.deepEqual(toggleRight([], 'manage_roles'),['manage_roles','view_roles']);
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const RolePermissions = require('../src/components/RolePermissions').default;
const html=renderToStaticMarkup(React.createElement(RolePermissions,{permissions:['view_roles'],editable:false,query:'',onlyEnabled:false,onChange(){}}));
assert.ok(!html.includes('type="checkbox"'));
assert.ok(!html.includes('Общий доступ'));
let rights=['view_roles'];
const originalLoad=Module._load;
Module._load=function(name,parent,isMain){if(name==='../store/useStore')return {useStore:()=>({roles:[{id:'r',name:'Тестовая роль',description:'Проверка',permissions:['view_roles'],isSystem:false}],users:[],hasPermission:key=>hasRight(rights,key)})};return originalLoad.apply(this,arguments)};
const RolesPage=require('../src/pages/RolesPage').default;
let readonly=renderToStaticMarkup(React.createElement(RolesPage));
assert.ok(readonly.includes('Роли и права доступа'));
assert.ok(!readonly.includes('>Редактировать</button>'));
assert.ok(!readonly.includes('aria-label="Удалить роль"'));
rights=[];
assert.ok(renderToStaticMarkup(React.createElement(RolesPage)).includes('Нет доступа'));
rights=['view_roles','manage_roles'];
assert.ok(renderToStaticMarkup(React.createElement(RolesPage)).includes('>Редактировать</button>'));
console.log(`PASS: frontend access, role readonly/admin rendering, ${keys.length} unique permissions`);
